// Crea una calculadora simple que permita realizar operaciones matemáticas básicas: suma, resta, multiplicación y división.

//SUMA
function sum(a, b) {
    return a + b;
}
let resultSum = sum(20, 23);
console.log("El resultado de la suma es: " + resultSum);

//RESTA
function subtract(a, b) {
    return a - b;
}
let resultSubtract = subtract(20, 23);
console.log("El resultado de la resta es: " + resultSubtract);

//MULTIPLICACION
function multiply(a, b) {
    return a * b;
}
let resultMultiply = multiply(8, 6);
console.log("El resultado de la multiplicación es: " + resultMultiply);

//DIVISION
function divide(a, b) {
    return a / b;
}
let resultDivide = divide(20, 3);
console.log("El resultado de la division es: " + resultDivide);
//Algoritmo sea la tabla de multiplicar del 8

let numero = 8;
let i = 1; //contador

while (i <= 10) { // condición: mientras i sea menor o igual a 10, el bloque de código se va a ejecutar
    console.log(numero + "x" + i + "=" + (numero * i)); // esto se va a imprimir en pantalla, el resultado de multiplicar la variable numero por el contador i
    i++; // incremento en 1 
}